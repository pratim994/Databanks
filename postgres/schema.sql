-- Repair delete before-images produced before REPLICA IDENTITY FULL was enabled.
-- The preceding CDC version is the last known source state for that business key.
WITH prior AS (
    SELECT d.event_id, p.first_name, p.last_name, p.email, p.created_at, p.payload
    FROM raw.customers d
    JOIN LATERAL (
        SELECT first_name, last_name, email, created_at, payload
        FROM raw.customers p
        WHERE p.customer_id = d.customer_id
          AND p.kafka_topic = d.kafka_topic
          AND p.kafka_partition = d.kafka_partition
          AND p.kafka_offset < d.kafka_offset
          AND p.operation_type <> 'd'
        ORDER BY p.kafka_offset DESC
        LIMIT 1
    ) p ON TRUE
    WHERE d.operation_type = 'd'
      AND (d.first_name IS NULL OR d.last_name IS NULL OR d.email IS NULL OR d.created_at IS NULL)
)
UPDATE raw.customers d
SET first_name = p.first_name, last_name = p.last_name, email = p.email,
    created_at = p.created_at, payload = p.payload
FROM prior p WHERE d.event_id = p.event_id;

WITH prior AS (
    SELECT d.event_id, p.customer_id, p.account_type, p.balance, p.currency, p.created_at, p.payload
    FROM raw.accounts d
    JOIN LATERAL (
        SELECT customer_id, account_type, balance, currency, created_at, payload
        FROM raw.accounts p
        WHERE p.account_id = d.account_id
          AND p.kafka_topic = d.kafka_topic
          AND p.kafka_partition = d.kafka_partition
          AND p.kafka_offset < d.kafka_offset
          AND p.operation_type <> 'd'
        ORDER BY p.kafka_offset DESC
        LIMIT 1
    ) p ON TRUE
    WHERE d.operation_type = 'd'
      AND (d.customer_id = 0 OR d.account_type IS NULL OR d.balance IS NULL OR d.currency IS NULL OR d.created_at IS NULL)
)
UPDATE raw.accounts d
SET customer_id = p.customer_id, account_type = p.account_type, balance = p.balance,
    currency = p.currency, created_at = p.created_at, payload = p.payload
FROM prior p WHERE d.event_id = p.event_id;

WITH prior AS (
    SELECT d.event_id, p.account_id, p.txn_type, p.amount, p.related_account_id,
           p.status, p.created_at, p.payload
    FROM raw.transactions d
    JOIN LATERAL (
        SELECT account_id, txn_type, amount, related_account_id, status, created_at, payload
        FROM raw.transactions p
        WHERE p.transaction_id = d.transaction_id
          AND p.kafka_topic = d.kafka_topic
          AND p.kafka_partition = d.kafka_partition
          AND p.kafka_offset < d.kafka_offset
          AND p.operation_type <> 'd'
        ORDER BY p.kafka_offset DESC
        LIMIT 1
    ) p ON TRUE
    WHERE d.operation_type = 'd'
      AND (d.account_id = 0 OR d.txn_type IS NULL OR d.amount IS NULL OR d.amount <= 0
           OR d.status IS NULL OR d.created_at IS NULL)
)
UPDATE raw.transactions d
SET account_id = p.account_id, txn_type = p.txn_type, amount = p.amount,
    related_account_id = p.related_account_id, status = p.status,
    created_at = p.created_at, payload = p.payload
FROM prior p WHERE d.event_id = p.event_id;
