CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    account_type VARCHAR(50) NOT NULL,
    balance NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    currency CHAR(3) NOT NULL DEFAULT 'USD',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    txn_type VARCHAR(50) NOT NULL CHECK (txn_type IN ('DEPOSIT','WITHDRAWAL','TRANSFER')),
    amount NUMERIC(18,2) NOT NULL CHECK (amount > 0),
    related_account_id BIGINT REFERENCES accounts(id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'COMPLETED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_transactions_account_created ON transactions(account_id, created_at);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'transactions_related_account_id_fkey') THEN
        ALTER TABLE transactions
            ADD CONSTRAINT transactions_related_account_id_fkey
            FOREIGN KEY (related_account_id) REFERENCES accounts(id) ON DELETE SET NULL NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'transactions_txn_type_check') THEN
        ALTER TABLE transactions
            ADD CONSTRAINT transactions_txn_type_check
            CHECK (txn_type IN ('DEPOSIT','WITHDRAWAL','TRANSFER')) NOT VALID;
    END IF;
END $$;

ALTER TABLE transactions VALIDATE CONSTRAINT transactions_related_account_id_fkey;
ALTER TABLE transactions VALIDATE CONSTRAINT transactions_txn_type_check;

-- PostgreSQL's default replica identity only logs primary keys for deletes.
-- FULL is needed for Debezium to preserve complete delete before-images.
ALTER TABLE customers REPLICA IDENTITY FULL;
ALTER TABLE accounts REPLICA IDENTITY FULL;
ALTER TABLE transactions REPLICA IDENTITY FULL;

CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS analytics;

CREATE TABLE IF NOT EXISTS raw.ingested_files (
    bucket TEXT NOT NULL,
    object_key TEXT NOT NULL,
    etag TEXT NOT NULL,
    table_name TEXT NOT NULL CHECK (table_name IN ('customers','accounts','transactions')),
    ingestion_timestamp TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    processing_status TEXT NOT NULL CHECK (processing_status IN ('processing','processed','failed')),
    error_message TEXT,
    row_count BIGINT,
    PRIMARY KEY (bucket, object_key)
);

